#!/bin/sh
# Rebuilds the site's fixtures from the real lab PCAPs. Run from anywhere after `cmake --build build`.
#   site/lib/lab.js         sensor observations per scenario (zerohour show --json)
#   site/data/evidence.json Wireshark (tshark) packet list + TLS dissection of the Certificate messages
#   site/data/bench.json    C++ sensor timings, bench/before.jsonl (plan) and bench/after.jsonl (tuned)
#   site/pcaps/*.pcap       the captures themselves, to open in Wireshark
set -e
cd "$(dirname "$0")/../.."
T=${TSHARK:-$(command -v tshark || echo /Applications/Wireshark.app/Contents/MacOS/tshark)}
export TZ=UTC
mkdir -p site/data site/pcaps
cp lab/pcaps/*.pcap site/pcaps/

{ echo "// Generated by site/scripts/fixtures.sh from lab/pcaps/*.pcap (zerohour show --json). Do not edit."
  echo "export const LAB = {"
  for s in learn normal onechange multichange attack; do
    printf '  %s: ' $s; ./build/zerohour show lab/pcaps/$s.pcap --json | tr -d '\n'; echo ','
  done
  echo "};"; } > site/lib/lab.js

python3 -I - "$T" > site/data/evidence.json <<'PY'
import json, subprocess, sys
T = sys.argv[1]
def tshark(*a): return subprocess.run([T, *a], check=True, capture_output=True, text=True).stdout
cols = ["no", "time", "src", "dst", "ttl", "proto", "len", "info", "sni", "names"]
out = {"tshark": tshark("--version").splitlines()[0], "captures": {}}
for cap in ["learn", "multichange", "attack"]:
    f = f"lab/pcaps/{cap}.pcap"
    rows = tshark("-r", f, "-Y", "tls.handshake", "-T", "fields", "-E", "separator=/t", *sum((["-e", e] for e in [
        "frame.number", "frame.time_relative", "ip.src", "ip.dst", "ip.ttl", "_ws.col.Protocol", "frame.len", "_ws.col.Info",
        "tls.handshake.extensions_server_name", "x509sat.uTF8String"]), []))
    pkts = [dict(zip(cols, r.split("\t"))) for r in rows.splitlines()]
    cert = next(p for p in pkts if "Certificate" in p["info"])
    tree = tshark("-r", f, "-2", "-Y", f"frame.number=={cert['no']}", "-O", "tls", "-V")
    lines = [l for l in tree.splitlines() if l.strip() and "Certificate [" not in l and "Random" not in l]
    out["captures"][cap] = {"file": f"pcaps/{cap}.pcap", "filter": "tls.handshake", "packets": pkts,
                            "detail_frame": cert["no"], "detail": lines[:120]}
json.dump(out, sys.stdout, indent=1)
PY

python3 -I - > site/data/bench.json <<'PY'
import json, platform, subprocess
cpu = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True).stdout.strip() or platform.processor()
rd = lambda f: [json.loads(l) for l in open(f)]
json.dump({"machine": cpu, "before": rd("bench/before.jsonl"), "after": rd("bench/after.jsonl")}, open("/dev/stdout", "w"), indent=1)
PY
echo "fixtures written"
